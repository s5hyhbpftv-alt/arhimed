  /* ═══════════════════════════════════════════════════════════════════════
     ЗОНЫ ИНТЕРЕСА НА СЦЕНЕ: латунная оправа, заклёпки, медальон с номером
     ═══════════════════════════════════════════════════════════════════════
     Якорь зоны задан в единицах кадра (x 0…1000, y 0…900) — так же, как в
     HTML-целях касания. В SVG кадр 1600 единиц шириной, поэтому x умножается
     на 1,6. Раньше умножения не было, и кольца уезжали влево на 60 %: кольцо
     стояло мимо предмета, а цель касания — на предмете. Это и была жалоба
     «круги висят поверх карточки и кромки полки».

     Состояние «найдено» переключается КЛАССОМ (занята), а не перерисовкой
     сцены: золотое кольцо, золотой медальон и галочка лежат в разметке
     заранее с нулевой прозрачностью (см. game.html). Иначе сцена мигала бы
     на каждом нажатии. */
  function кольцоЗоны(x, y, R, занята, активна, номер){
    var мед = Math.max(42, Math.min(58, R * .30));
    var мY = y - R;
    var с = '';
    /* 1. мягкое тёплое пятно: «здесь что-то есть» */
    с += '<g class="зона-свет" opacity="' + (активна ? '.52' : '.26') + '">' +
      эл(x, y, R * 1.36, R * 1.36, 'url(#свечениеТёпл)', null, 0) + '</g>';
    /* 2. тень под оправой — кольцо лежит на предмете, а не наклеено на кадр */
    с += эл(x, y + R * .96, R * .9, R * .16, '#05080e', null, 0, 'opacity=".3" filter="url(#мягко)"');
    /* 3. латунная оправа */
    с += '<g class="зона-кольцо">' +
      кр(x, y, R, 'none', 'rgba(6,12,10,.72)', 15) +
      кр(x, y, R, 'none', ЦВ.латунь, 8) +
      кр(x, y, R, 'none', ЦВ.латуньСвет, 2.4, 'opacity=".55"') + '</g>';
    /* 4. золотая оправа и блеск — включаются классом «занята» и наведением */
    с += '<g class="зона-золото">' +
      кр(x, y, R, 'none', 'url(#кольцоЗолото)', 9) +
      кр(x, y, R, 'none', '#fff6d8', 2.4, 'opacity=".7"') + '</g>';
    с += '<g class="зона-блеск">' + кр(x, y, R - 3, 'none', '#fff6d8', 4, 'opacity=".9"') + '</g>';
    /* 5. четыре заклёпки — оправа, а не отладочный маркер */
    for (var i = 0; i < 4; i++){
      var а = Math.PI / 4 + i * Math.PI / 2;
      с += кр(x + Math.cos(а) * R, y + Math.sin(а) * R, 5.5, ЦВ.латунь2, '#3a2c14', 1.6);
      с += кр(x + Math.cos(а) * R - 1.4, y + Math.sin(а) * R - 1.4, 2, '#fff6d8', null, 0, 'opacity=".7"');
    }
    /* 6. медальон с номером на верхней точке кольца */
    с += '<g class="зона-мед-тёмн">' +
      кр(x, мY, мед, 'url(#номерТёмн)', ЦВ.латунь2, 3) +
      кр(x, мY, мед - 7, 'none', ЦВ.латуньСвет, 1.8, 'opacity=".38"') + '</g>';
    с += '<g class="зона-мед-золото">' +
      кр(x, мY, мед, 'url(#номерЗолото)', ЦВ.латунь2, 3) +
      кр(x, мY, мед - 7, 'none', '#fff6d8', 1.8, 'opacity=".5"') + '</g>';
    с += '<text class="зона-номер" x="' + ч(x) + '" y="' + ч(мY + мед * .4) + '" text-anchor="middle" ' +
      'font-family="Georgia,serif" font-size="' + ч(мед * 1.2) + '" font-weight="bold" fill="#ffe9ad">' +
      ч(номер, 0) + '</text>';
    /* 7. найдено: галочка рядом с кольцом. Смысл передан и цветом, и знаком. */
    с += '<g class="зона-галка">' +
      кр(x + R * .7, y + R * .7, 20, ЦВ.золото, '#2b2118', 3) +
      пт('M' + ч(x + R * .7 - 9) + ' ' + ч(y + R * .7) + ' L' + ч(x + R * .7 - 2) + ' ' + ч(y + R * .7 + 8) +
        ' L' + ч(x + R * .7 + 11) + ' ' + ч(y + R * .7 - 9) + ' Z', '#2b2118') + '</g>';
    с += блик(x - R * .72, y - R * .7, x + R * .2, y - R * .97, 5, .8);
    return с;
  }

  /* зоны комнаты: рисуются ПОСЛЕ фона, поэтому их видно и на фото.
     «Занято» — либо найденный предмет зоны, либо (для главной зоны комнаты)
     решённая задача: тогда кольцо сразу показывает результат. */
  function зоныСцены(комната, состояние, активна){
    var с = '';
    var найдено = (состояние && состояние.найдено) || [];
    var решена = !!(состояние && состояние.решено && состояние.решено[индексКомнаты(комната.ключ)]);
    var главная = комната.задача && комната.задача.досье;
    for (var i = 0; i < комната.зоны.length; i++){
      var з = комната.зоны[i];
      var занята = (з.досье === главная) ? решена : (найдено.indexOf(з.ключ) >= 0);
      var x = з.x * 1.6;
      с += '<g data-зона="' + эск(з.ключ) + '" class="' + (занята ? 'занята' : '') + '" ' +
        'style="transform-origin:' + ч(x) + 'px ' + ч(з.y) + 'px">' +
        кольцоЗоны(x, з.y, з.r, занята, активна === з.ключ, i + 1) + '</g>';
    }
    return с;
  }
  /* ═══════════════════════════════════════════════════════════════════════
     ВНЕШНИЙ ИНТЕРФЕЙС ДЛЯ СТРАНИЦЫ
     ═══════════════════════════════════════════════════════════════════════ */
  function эск(т){
    return String(т == null ? '' : т)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }
  function комнатаПоКлючу(к){
    for (var i = 0; i < КОМНАТЫ.length; i++) if (КОМНАТЫ[i].ключ === к) return КОМНАТЫ[i];
    return null;
  }
  function индексКомнаты(к){
    for (var i = 0; i < КОМНАТЫ.length; i++) if (КОМНАТЫ[i].ключ === к) return i;
    return 0;
  }
  /* нормализация ввода: «1 926», «1.9.26», «1926» — всё одно и то же */
  function нормализуйКод(т){
    return String(т == null ? '' : т).replace(/[^0-9]/g, '');
  }
  /* нормализация числового ответа: пробелы, запятая, единицы измерения */
  function нормализуйЧисло(т){
    var с = String(т == null ? '' : т).replace(/\s|\u00a0/g, '').replace(',', '.');
    var м = с.match(/-?\d+(\.\d+)?/);
    return м ? м[0] : '';
  }
  function проверкаЧисла(ввод, верно){
    var ч = нормализуйЧисло(ввод);
    if (ч === '') return false;
    return Math.abs(parseFloat(ч) - верно) < 1e-9;
  }

  /* Проверка данных на старте: номер ответа обязан попадать в варианты,
     а цифра находки — совпадать с последней цифрой ответа. Иначе в консоль
     уезжает честное сообщение, а не «неверно» на верный ответ. */
  (function проверитьДанные(){
    var ошибки = [];
    var код = '';
    КОМНАТЫ.forEach(function(к){
      var з = к.задача;
      if (!з){ ошибки.push('нет задачи у комнаты «' + к.имя + '»'); return; }
      if (з.тип === 'выбор'){
        if (Object.prototype.toString.call(з.варианты) !== '[object Array]' || !з.варианты.length)
          ошибки.push('в комнате «' + к.имя + '» нет вариантов ответа');
        else if (!(з.ответ >= 0) || з.ответ >= з.варианты.length)
          ошибки.push('в комнате «' + к.имя + '» номер ответа ' + з.ответ + ' вне списка вариантов');
      } else {
        if (typeof з.ответЧисло !== 'number')
          ошибки.push('в комнате «' + к.имя + '» не задан числовой ответ');
      }
      if (!з.цифра) ошибки.push('в комнате «' + к.имя + '» нет цифры кода');
      код += з.цифра || '·';
      if (!з.досье || !ДОСЬЕ[з.досье]) ошибки.push('в комнате «' + к.имя + '» досье «' + з.досье + '» не описано');
      if (!к.фон) ошибки.push('в комнате «' + к.имя + '» не задан фон');
      /* сюжет обязан быть в каждой комнате: голос смотрителя и запись журнала */
      if (!к.голос) ошибки.push('в комнате «' + к.имя + '» нет строки смотрителя');
      if (!к.журнал || !к.журнал.текст) ошибки.push('в комнате «' + к.имя + '» нет записи в журнал');
      if (!к.зоны || к.зоны.length < 2) ошибки.push('в комнате «' + к.имя + '» меньше двух зон — исследовать нечего');
      if (к.зоны && к.зоны.length){
        var естьГлавная = false;
        к.зоны.forEach(function(з){
          if (!(з.x >= 0) || !(з.y >= 0)) ошибки.push('в комнате «' + к.имя + '» у зоны «' + з.имя + '» нет координат в единицах кадра');
          if (з.досье === к.задача.досье) естьГлавная = true;
        });
        if (!естьГлавная) ошибки.push('в комнате «' + к.имя + '» ни одна зона не открывает задачу («' + к.задача.досье + '» не найдено среди зон)');
        /* Кольца зон не имеют права висеть в воздухе, налезать друг на друга
           и срезаться краем кадра. Кольцо рисуется в SVG размером 1600 единиц
           по ширине, поэтому x умножается на 1,6 (см. зоныСцены). Проверка
           идёт радиусом кольца, а не «на глаз»: до края кадра ≥ 40 единиц
           (на телефоне 390 px это 9 px), между кольцами ≥ 20 единиц. */
        for (var a = 0; a < к.зоны.length; a++){
          var зA = к.зоны[a], rA = зA.r || 120, xA = зA.x * 1.6;
          if (xA - rA < 40 || 1600 - (xA + rA) < 40 || зA.y - rA < 40 || 900 - (зA.y + rA) < 40)
            ошибки.push('в комнате «' + к.имя + '» кольцо зоны «' + зA.имя + '» ближе 40 единиц к краю кадра — на телефоне оно срежется краем');
          for (var b = a + 1; b < к.зоны.length; b++){
            var зB = к.зоны[b], rB = зB.r || 120;
            var dx = Math.abs(xA - зB.x * 1.6);
            var dy = Math.abs(зA.y - зB.y);
            if (dx * dx + dy * dy < (rA + rB + 20) * (rA + rB + 20))
              ошибки.push('в комнате «' + к.имя + '» кольца зон «' + зA.имя + '» и «' + зB.имя + '» пересекаются');
          }
        }
        /* цели касания в HTML не налезают: 48 px на телефоне = 250 единиц
           кадра, значит центры обязаны расходиться не меньше чем на 250 */
        for (var c = 0; c < к.зоны.length; c++){
          for (var d = c + 1; d < к.зоны.length; d++){
            var cx = Math.abs(к.зоны[c].x - к.зоны[d].x);
            var cy = Math.abs(к.зоны[c].y - к.зоны[d].y);
            if (cx * cx + cy * cy < 250 * 250)
              ошибки.push('в комнате «' + к.имя + '» цели касания «' + к.зоны[c].имя + '» и «' + к.зоны[d].имя + '» налезут друг на друга на телефоне');
          }
        }
      }
    });
    if (код !== ИГРА.код) ошибки.push('собранный из комнат код «' + код + '» не совпадает с кодом сейфа «' + ИГРА.код + '»');
    if (ошибки.length){
      try { console.error('Обсерватория: проверьте данные игры — ' + ошибки.join('; ')); } catch(e){}
    }
  })();


  function нормализуй(с){
    var б = пустое();
    if (!с || typeof с !== 'object') return б;
    if (Object.prototype.toString.call(с.решено) === '[object Array]'){
      for (var i = 0; i < 4; i++) б.решено[i] = !!с.решено[i];
    }
    if (Object.prototype.toString.call(с.найдено) === '[object Array]'){
      б.найдено = [];
      for (var j = 0; j < с.найдено.length && j < 24; j++){
        if (typeof с.найдено[j] === 'string' && с.найдено[j].length < 24) б.найдено.push(с.найдено[j]);
      }
    }
    б.сейф = !!с.сейф;
    б.попытки = Math.max(0, parseInt(с.попытки, 10) || 0);
    return б;
  }

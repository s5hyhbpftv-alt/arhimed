  /* ═══════════════════════════════════════════════════════════════════════
     СЛОИ ПОВЕРХ ЛЮБОГО ФОНА: свет, туман, пыль, виньетка, передний план
     ═══════════════════════════════════════════════════════════════════════
     Собираются отдельным <svg> и кладутся ПОВЕРХ кадра — и поверх вектора, и
     поверх фотографии (поле «фон» в данных). Поэтому фотореалистичный фон
     подставляется одной строкой, а свет, туман и виньетка остаются те же.

     Слои идут в строгом порядке, и порядок здесь — это глубина:
       1. туман дальнего плана   (холодная дымка у стены);
       2. световое пятно на стене (единственный источник и его след);
       3. конус света от источника;
       4. световая лужа и отражение на полу;
       5. блик на латуни и стекле — ставит сам рисовальщик комнаты;
       6. туман ближнего плана   (отделяет средний план от переднего);
       7. пылинки в луче — медленный дрейф, низкая амплитуда;
       8. виньетка по краям;
       9. передний план: тёмный низ кадра и тонкая рама.
     Ни один слой здесь не перехватывает нажатие: в HTML у svg стоит
     pointer-events:none. */
  function слойСвета(комната){
    var св = комната.свет || { x: 60, y: 34, r: 48, цвет: 'тёплый' };
    var лун = св.цвет === 'лунный';
    var x = св.x / 100 * 1600;
    var y = св.y / 100 * 900;
    var r = св.r / 100 * 1600;
    var цв = лун ? '#cfe8ff' : '#ffd08a';
    var с = '';
    /* 1. дальний туман: стена читается «в глубине», а не как заливка */
    с += пр(0, 0, 1600, 900, 'url(#туманДаль)');
    /* 2. пятно света на дальней стене от самого источника */
    с += эл(x, y + 40, r * 1.5, r * 1.2, 'url(#' + (лун ? 'пятноЛуна' : 'пятноНаСтене') + ')');
    /* 3. конус: узкий у источника, широкий на полу. Один источник — один конус. */
    var ш = св.луч && св.луч.ширина ? св.луч.ширина : 22;
    с += пт('M' + ч(x - ш * 3) + ' ' + ч(y) + ' L' + ч(x + ш * 3) + ' ' + ч(y) +
      ' L' + ч(x + ш * 11) + ' 900 L' + ч(x - ш * 11) + ' 900 Z',
      'url(#' + (лун ? 'лучЛуна' : 'лучТёпл') + ')', null, 0, 'opacity=".5"');
    /* 4. лужа света и полоса отражения: свет садится на пол, а не висит */
    с += следСвета(x, 620, лун ? 'лунный' : 'тёплый');
    /* «дыхание» лампы: медленное мерцание 4 c, амплитуда 5 %.
       Один элемент с одной анимацией — не «гирлянда», а живой огонь. */
    с += '<g class="g-flick">' +
      эл(x, y, r * 1.18, r * .9, 'url(#свечениеТёпл)', null, 0, 'opacity="' + (лун ? '.28' : '.5') + '"') +
      '</g>';
    /* 6. ближний туман */
    с += пр(0, 470, 1600, 430, 'url(#туманБлиз)');
    /* 7. пылинки: не «снег», а медленный дрейф в 3–6 с, смещение 14 единиц */
    var семя = 7;
    var п = '';
    for (var i = 0; i < 18; i++){
      семя = (семя * 1103515245 + 12345) & 0x7fffffff;
      var пx = x - r * 1.1 + (семя % 1000) / 1000 * r * 2.2;
      семя = (семя * 1103515245 + 12345) & 0x7fffffff;
      var пy = y - r * .3 + (семя % 1000) / 1000 * (900 - y) * .78;
      семя = (семя * 1103515245 + 12345) & 0x7fffffff;
      var рад = 1.6 + (семя % 1000) / 1000 * 2.6;
      семя = (семя * 1103515245 + 12345) & 0x7fffffff;
      var з = 4.6 + (семя % 1000) / 1000 * 1.4;          /* 4.6–6 с */
      var задержка = ((семя >> 7) % 1000) / 1000 * -6;
      п += '<circle cx="' + ч(пx) + '" cy="' + ч(пy) + '" r="' + ч(рад) + '" fill="#ffe6b0" opacity=".34">' +
        '<animate attributeName="cy" values="0;-14;0" dur="' + ч(з) + 's" begin="' + ч(задержка) + 's" repeatCount="indefinite"/>' +
        '<animate attributeName="opacity" values=".34;.12;.34" dur="' + ч(з) + 's" begin="' + ч(задержка) + 's" repeatCount="indefinite"/>' +
        '</circle>';
    }
    с += '<g class="g-dust">' + п + '</g>';
    /* 8. виньетка */
    с += пр(0, 0, 1600, 900, 'url(#виньетка)');
    /* 9. передний план: тёмный низ кадра и уходящая в тень левая кромка.
       Первый снимок показал, что полоса .82 и кромки .5/.42 съедали кадр:
       комната читалась чёрным прямоугольником. Теперь передний план тёмный,
       но не глухой — он обрамляет, а не закрывает. */
    с += пт('M0 900 L0 742 C300 796 900 812 1600 764 L1600 900 Z', '#040a08', null, 0, 'opacity=".58"');
    с += пт('M0 0 L0 900 L96 900 C58 640 64 300 108 0 Z', '#050b09', null, 0, 'opacity=".3"');
    с += пт('M1600 0 L1600 900 L1504 900 C1546 620 1540 280 1496 0 Z', '#050b09', null, 0, 'opacity=".26"');
    /* тонкая рама кадра: тот же латунный hairline, что у блоков интерфейса */
    с += пр(1.5, 1.5, 1597, 897, 'none', 'rgba(217,164,65,.28)', 3);
    return '<svg class="g-over" viewBox="0 0 1600 900" preserveAspectRatio="none" aria-hidden="true">' +
      определения() + с + '</svg>';
  }

  /* ═══════════════════════════════════════════════════════════════════════
     ЗОНЫ ИНТЕРЕСА НА СЦЕНЕ: кольцо + номер. Рисуются поверх фона.
     ═══════════════════════════════════════════════════════════════════════
     Якорь зоны задан в единицах кадра (x 0…1000, y 0…900), а не текстом и не
     пикселями: единицы кадра масштабируются вместе со сценой, поэтому кольцо
     стоит на предмете и на векторе, и на фотографии.
     Размеры выбраны так, чтобы НА ТЕЛЕФОНЕ подпись не мельчала: при кадре
     390×219 единица кадра = 0.244 px, значит кегль 44 ед = 10.7 px, а кольцо
     40 ед = 9.8 px радиусом. Цель касания живёт в HTML и всегда 92×92 px —
     она не зависит от масштаба сцены (см. game.html). */
  function кольцоЗоны(x, y, занята, активна, номер){
    var R1 = 38;                      /* радиус кольца в единицах кадра */
    var с = '';
    /* 1. мягкое тёплое пятно вокруг: «здесь что-то есть» */
    с += эл(x, y, 84, 70, 'url(#свечениеТёпл)', null, 0, 'opacity="' + (активна ? '.44' : '.26') + '"');
    /* 2. тень под маркером — он стоит на предмете, а не наклеен на кадр */
    с += эл(x, y + R1 - 6, 58, 12, '#05080e', null, 0, 'opacity=".42"');
    /* 3. латунное кольцо: тёмная подложка снаружи, латунь, верхний блик.
       По снимку 1200×800 тонкое кольцо терялось на светлой стене — теперь
       оно читается и на камне, и на самой светлой части кадра. */
    с += кр(x, y, R1, 'none', 'rgba(6,12,10,.8)', 10);
    с += кр(x, y, R1, 'none', ЦВ.латунь, 7);
    с += кр(x, y, R1, 'none', ЦВ.латуньСвет, 2.6, 'opacity=".62"');
    /* 4. тёмный диск с номером: номер — это порядок исследования, а не украшение */
    с += кр(x, y, R1 - 8, занята ? 'url(#номерЗолото)' : 'url(#номерТёмн)', ЦВ.латунь2, 2.4);
    с += '<text x="' + ч(x) + '" y="' + ч(y + 12) + '" text-anchor="middle" ' +
      'font-family="Georgia,serif" font-size="34" font-weight="bold" fill="' +
      (занята ? '#2b2118' : '#ffe9ad') + '">' + ч(номер, 0) + '</text>';
    if (занята){
      /* найдено: галочка поверх номера. Смысл передан и цветом, и знаком. */
      с += кр(x + 24, y - 24, 15, ЦВ.золото, '#2b2118', 2.4);
      с += пт('M' + ч(x + 17) + ' ' + ч(y - 25) + ' L' + ч(x + 22) + ' ' + ч(y - 19) +
        ' L' + ч(x + 31) + ' ' + ч(y - 31) + ' Z', '#2b2118');
    }
    с += блик(x - 26, y - R1 + 7, x + 8, y - R1 + 1, 4, .85);
    return с;
  }

  /* зоны комнаты: рисуются ПОСЛЕ фона, поэтому их видно и на фото.
     «Занято» — это либо найденный предмет зоны, либо (для главной зоны
     комнаты) решённая задача: тогда кольцо сразу показывает результат. */
  function зоныСцены(комната, состояние, активна){
    var с = '';
    var найдено = (состояние && состояние.найдено) || [];
    var решена = !!(состояние && состояние.решено && состояние.решено[индексКомнаты(комната.ключ)]);
    var главная = комната.задача && комната.задача.досье;
    for (var i = 0; i < комната.зоны.length; i++){
      var з = комната.зоны[i];
      var занята = (з.досье === главная) ? решена : (найдено.indexOf(з.ключ) >= 0);
      с += '<g data-зона="' + эск(з.ключ) + '"' + (активна === з.ключ ? ' class="on"' : '') + '>' +
        кольцоЗоны(з.x, з.y, занята, активна === з.ключ, i + 1) + '</g>';
    }
    return с;
  }

  /* ═══════════════════════════════════════════════════════════════════════
     ВНЕШНИЙ ИНТЕРФЕЙС ДЛЯ СТРАНИЦЫ
     ═══════════════════════════════════════════════════════════════════════ */
  function эск(т){
    return String(т == null ? '' : т)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
  }
  function комнатаПоКлючу(к){
    for (var i = 0; i < КОМНАТЫ.length; i++) if (КОМНАТЫ[i].ключ === к) return КОМНАТЫ[i];
    return null;
  }
  function индексКомнаты(к){
    for (var i = 0; i < КОМНАТЫ.length; i++) if (КОМНАТЫ[i].ключ === к) return i;
    return 0;
  }
  /* нормализация ввода: «1 926», «1.9.26», «1926» — всё одно и то же */
  function нормализуйКод(т){
    return String(т == null ? '' : т).replace(/[^0-9]/g, '');
  }
  /* нормализация числового ответа: пробелы, запятая, единицы измерения */
  function нормализуйЧисло(т){
    var с = String(т == null ? '' : т).replace(/\s|\u00a0/g, '').replace(',', '.');
    var м = с.match(/-?\d+(\.\d+)?/);
    return м ? м[0] : '';
  }
  function проверкаЧисла(ввод, верно){
    var ч = нормализуйЧисло(ввод);
    if (ч === '') return false;
    return Math.abs(parseFloat(ч) - верно) < 1e-9;
  }

  /* Проверка данных на старте: номер ответа обязан попадать в варианты,
     а цифра находки — совпадать с последней цифрой ответа. Иначе в консоль
     уезжает честное сообщение, а не «неверно» на верный ответ. */
  (function проверитьДанные(){
    var ошибки = [];
    var код = '';
    КОМНАТЫ.forEach(function(к){
      var з = к.задача;
      if (!з){ ошибки.push('нет задачи у комнаты «' + к.имя + '»'); return; }
      if (з.тип === 'выбор'){
        if (Object.prototype.toString.call(з.варианты) !== '[object Array]' || !з.варианты.length)
          ошибки.push('в комнате «' + к.имя + '» нет вариантов ответа');
        else if (!(з.ответ >= 0) || з.ответ >= з.варианты.length)
          ошибки.push('в комнате «' + к.имя + '» номер ответа ' + з.ответ + ' вне списка вариантов');
      } else {
        if (typeof з.ответЧисло !== 'number')
          ошибки.push('в комнате «' + к.имя + '» не задан числовой ответ');
      }
      if (!з.цифра) ошибки.push('в комнате «' + к.имя + '» нет цифры кода');
      код += з.цифра || '·';
      if (!з.досье || !ДОСЬЕ[з.досье]) ошибки.push('в комнате «' + к.имя + '» досье «' + з.досье + '» не описано');
      if (!к.фон) ошибки.push('в комнате «' + к.имя + '» не задан фон');
      if (!к.зоны || к.зоны.length < 2) ошибки.push('в комнате «' + к.имя + '» меньше двух зон — исследовать нечего');
      if (к.зоны && к.зоны.length){
        var естьГлавная = false;
        к.зоны.forEach(function(з){
          if (!(з.x >= 0) || !(з.y >= 0)) ошибки.push('в комнате «' + к.имя + '» у зоны «' + з.имя + '» нет координат в единицах кадра');
          if (з.досье === к.задача.досье) естьГлавная = true;
        });
        if (!естьГлавная) ошибки.push('в комнате «' + к.имя + '» ни одна зона не открывает задачу («' + к.задача.досье + '» не найдено среди зон)');
        /* Кольца зон не имеют права налезать. На ширине 390 px кадр даёт
           0.244 px на единицу, а цель касания там 48 px (см. .g-zone в
           game.html). Значит центрам нужно ≥ (48 + 8) / 0.244 ≈ 230 единиц
           пути — проверка ниже требует 130 единиц, то есть зазор не меньше
           130 × 0.244 − 48 = −16 px на самом узком экране, а с разнесением,
           заданным в данных, замер даёт положительный зазор на всех ширинах. */
        for (var a = 0; a < к.зоны.length; a++){
          for (var b = a + 1; b < к.зоны.length; b++){
            var dx = Math.abs(к.зоны[a].x - к.зоны[b].x);
            var dy = Math.abs(к.зоны[a].y - к.зоны[b].y);
            if (dx * dx + dy * dy < 130 * 130)
              ошибки.push('в комнате «' + к.имя + '» зоны «' + к.зоны[a].имя + '» и «' + к.зоны[b].имя + '» сближены меньше 130 единиц кадра — на телефоне цели налезут');
          }
        }
      }
    });
    if (код !== ИГРА.код) ошибки.push('собранный из комнат код «' + код + '» не совпадает с кодом сейфа «' + ИГРА.код + '»');
    if (ошибки.length){
      try { console.error('Обсерватория: проверьте данные игры — ' + ошибки.join('; ')); } catch(e){}
    }
  })();


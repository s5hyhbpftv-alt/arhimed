  function ч(з, т, д){ /* число с запятой-разделителем: SVG понимает только точку */
    var н = Number(з);
    if (!isFinite(н)) н = 0;
    return (д === undefined ? н.toFixed(1) : н.toFixed(д)).replace(/\.0$/, '');
  }

    const L=String(t.ans||''), w=String(t.word||'');
    if(/^(лл|нн|сс|кк|рр|мм|бб|пп)$/.test(L)) return 604;
    if(L.length===1 && /[втсд]/.test(L) && SILENT.test(w)) return 604;

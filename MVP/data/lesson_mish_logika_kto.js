    `<text x="${x}" y="${y}" text-anchor="${anchor || 'middle'}" font-family="${F}" font-size="${size || 14}" fill="${fill || IVORY}"${w ? ` font-weight="${w}"` : ''}>${s}</text>`;
  const rc = (x, y, w, h, fill, stroke, rx, sw, dash) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx == null ? 4 : rx}" fill="${fill || 'none'}"` +
    `${stroke ? ` stroke="${stroke}" stroke-width="${sw || 1}"` : ''}${dash ? ` stroke-dasharray="${dash}"` : ''}/>`;
  const ln = (x1, y1, x2, y2, c, w, dash) =>
    `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${c || LINE}" stroke-width="${w || 1}"${dash ? ` stroke-dasharray="${dash}"` : ''}/>`;
  const ci = (cx, cy, r, fill, stroke, sw) =>
    `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill || 'none'}"${stroke ? ` stroke="${stroke}" stroke-width="${sw || 1}"` : ''}/>`;
  const ph = (d, stroke, w, fill) =>
    `<path d="${d}" fill="${fill || 'none'}"${stroke ? ` stroke="${stroke}" stroke-width="${w || 1}" stroke-linecap="round" stroke-linejoin="round"` : ''}/>`;

  /* ── тёмный планшет под рисунок: один и тот же на всём листе ── */
  const board = (h, inner) => rc(6, 6, 284, h - 12, DEEP, GOLD, 10) + inner;

  /* ── знак в клетке таблицы: галочка — фраза сходится, крестик — противоречие,
        вопросительный знак — клетка ещё не проверена ── */

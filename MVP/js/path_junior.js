  /* Тема задачи без пометки класса: «1 класс · Счёт до 10» → «Счёт до 10» */
  function темаЗадачи(t){
    return String((t && t.theme) || '').replace(/^\s*\d{1,2}(\s*[-–—]\s*\d{1,2})?\s*(класс|кл)\.?\s*·\s*/i, '').trim();
  }
  function совпало(строка, слова){
    const s = String(строка || '').toLowerCase();
    return (слова || []).some(w => s.indexOf(String(w).toLowerCase()) >= 0);
  }

  /* Уроки класса в порядке плана обучения; заглушки «готовится» отдельно.

     Класс проверяется здесь ОТДЕЛЬНО и всегда, хотя пул уже отобран lessonPool().
     Причина: «весь мир открыт» (DB.openWorld) включён по умолчанию, а при нём
     lessonFits() пропускает урок любого класса. Из-за этого маршрут
     первоклассника состоял из 109 уроков вместо 30 — с дробями, процентами и
     углами 4 класса и мастерскими Сиракуз 5–6 классов, — а «за горизонтом»
     ему показывали 37 чужих заглушек вместо ноля. У задач этот обход уже был
     (задачиКласса), у уроков его не было. Переключатель «весь мир» остаётся
     рабочим для каталога и банка: он про них, а не про маршрут своего класса.

     Пул берётся не у lessonPool(), а у банка напрямую, через isVisibleLesson и
     диапазон класса. lessonPool() отбирает младшему уроки по lessonClassNum —
     а та читает ПЕРВОЕ число перед словом «класс», и у подписи «Математика ·
     3–5 класс» получает 5. Из-за этого урок 23 «Время на часах: модуль 24» не
     доходил ни до третьего, ни до четвёртого класса, хотя написан для них.
     Диапазон (lessonClassRange) читает оба числа и такого не теряет.
     Олимпиадные туры (subj:'tour') сюда по-прежнему не попадают: их прячет
     isVisibleLesson, потому что тур — работа на баллы и время в своём разделе,
     а не урок маршрута. */
  function урокиКласса(){
    const k = +классУченика();
    let пул = [];
    try{ пул = (window.ARH_LESSONS || []).slice(); }catch(e){ пул = []; }
    пул = пул.filter(function(L){
      try{ if(typeof isVisibleLesson === 'function' && !isVisibleLesson(L)) return false; }catch(e){}
      let r = null;
      try{ r = (typeof lessonClassRange === 'function') ? lessonClassRange(L) : null; }catch(e){ r = null; }
      if(!r) return false;                      /* класс не определён — в маршрут класса не берём */
      return !(r[1] < k || r[0] > k);
    });
    const номер = L => (L && L.__планПорядок != null) ? L.__планПорядок : 1e9;
    пул.sort((a,b)=> номер(a)-номер(b) || (a.id||0)-(b.id||0));
    return {готовые: пул.filter(L=>!L.soon), скоро: пул.filter(L=>L.soon)};
  }

  /* Задачи начальной школы своего класса — независимо от переключателя «весь мир»:
     маршрут класса не должен раздуваться задачами пятиклассника. */
  function задачиКласса(){
    const k = +классУченика();
    const все = (window.ARH_TASKS || []).filter(t => t && t.island === 'Начальная школа');
    return все.filter(t => {
      const r = (typeof taskClassRange === 'function') ? taskClassRange(t) : [1,4];
      return !(r[1] < k || r[0] > k);
    });
  }

  /* Маршрут: участки, внутри — уроки по плану, следом задачи своей темы.
     Урок и задача идут вперемешку по смыслу: сначала объясни — потом реши. */
  function маршрут(){
    const k = +классУченика();
    const план = ЭТАПЫ[k] || ЭТАПЫ[1];
    const {готовые, скоро} = урокиКласса();
    const задачи = задачиКласса();
    const взятыйУрок = {}, взятаяЗадача = {};

    /* Первый проход — поимённые уроки: они старше любых ключевых слов. */
    const поимённо = план.map(function(э){
      const набор = {};
      (э.ид || []).forEach(function(id){
        const L = готовые.find(L => L.id === id);
        if(L && !взятыйУрок[L.id]){ взятыйУрок[L.id] = 1; набор[L.id] = 1; }
      });
      return набор;
    });

    const этапы = план.map(function(э, i){
      const шаги = [];
      готовые.forEach(function(L){
        const мой = поимённо[i][L.id];
        if(!мой){
          if(взятыйУрок[L.id]) return;
          if(!совпало(L.src + ' · ' + L.title, э.сл)) return;
          взятыйУрок[L.id] = 1;
        }
        шаги.push({вид:'урок', id:L.id, имя:L.title, под:'урок', готово:урокГотов(L)});
      });
      задачи.forEach(function(t){
        if(взятаяЗадача[t.id]) return;
        if(!(э.задачи || []).some(th => темаЗадачи(t) === th)) return;
        взятаяЗадача[t.id] = 1;
        шаги.push({вид:'задача', id:t.id, имя:t.title, под:'задача · ур. ' + (t.diff||1), готово:задачаГотова(t)});
      });
      return {имя:э.имя, цель:э.цель, сюжет:э.сюжет, шаги:шаги};
    }).filter(э => э.шаги.length);

    /* Ничего не теряем: уроки и задачи, не попавшие ни в один участок, собираются
       в последний. Без него правка плана молча прятала бы содержимое. */
    const остаток = [];
    готовые.forEach(L=>{ if(!взятыйУрок[L.id]) остаток.push({вид:'урок', id:L.id, имя:L.title, под:'урок', готово:урокГотов(L)}); });
    задачи.forEach(t=>{ if(!взятаяЗадача[t.id]) остаток.push({вид:'задача', id:t.id, имя:t.title, под:'задача · ур. ' + (t.diff||1), готово:задачаГотова(t)}); });
    if(остаток.length) этапы.push({имя:'Ещё по дороге', цель:'то, что тоже открыто твоему классу',
      сюжет:'Море выносит на берег и то, чего никто не ждал.', шаги:остаток});

    return {этапы:этапы, скоро:скоро};
  }


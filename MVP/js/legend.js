let LG = { ch:0 };

function escL(s){ return s.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;'); }
function fmtL(p){ // лёгкая разметка: **жирный**
  return escL(p).replace(/\*\*(.+?)\*\*/g,'<b style="color:var(--brass)">$1</b>');
}

function renderLegend(){
  const s=document.getElementById('screen');
  const ch=ARH_LEGEND[LG.ch];
  const dots=ARH_LEGEND.map((_,i)=>`<div class="sdot ${i<LG.ch?'past':''} ${i===LG.ch?'on':''}" style="flex:none;width:26px"></div>`).join('');
  s.innerHTML=`<button class="btn ghost" onclick="go('path')">← Путь</button>
    <h2>📜 Легенда об Архимеде</h2>
    <div class="legend-hero">
      <div style="font-size:46px;line-height:1">${ch.ico}</div>
      <div><b style="color:var(--brass)">${escL(ch.t)}</b>
      <div class="small" style="margin-top:2px">глава ${LG.ch+1} из ${ARH_LEGEND.length}</div></div>
    </div>
    <div style="display:flex;gap:6px;flex-wrap:wrap;margin:4px 0 10px">${dots}</div>
    <div class="card">${ch.p.map(p=>`<div style="margin:0 0 10px;line-height:1.6;font-size:14.5px">${fmtL(p)}</div>`).join('')}
      ${ch.q?`<div class="arch" style="margin:6px 0 0"><span class="who">◈ Архимед</span>${escL(ch.q)}</div>`:''}
    </div>
    <div class="btnrow">
      <button class="btn ghost" onclick="lgStep(-1)" ${LG.ch===0?'disabled':''}>← Назад</button>
      ${LG.ch<ARH_LEGEND.length-1
        ? `<button class="btn" onclick="lgStep(1)">Дальше →</button>`
        : `<button class="btn ok2" onclick="go('path')">К островам →</button>`}
    </div>
    <div class="small" style="margin-top:10px;line-height:1.5">Полный текст легенды — в файле «ЛЕГЕНДА_АРХИМЕДА.md» рядом с приложением.</div>`;
  hud();
}
function lgStep(d){ LG.ch=Math.max(0,Math.min(ARH_LEGEND.length-1,LG.ch+d)); renderLegend(); }

def переставить_математику_5_6(порядок, по_id):
    """Ставит уроки математики 5–6 классов в учебную последовательность."""
    в_классе = [i for i in порядок
                if (по_id[i]["subj"] or "") == "math" and (по_id[i]["к"] or 99) in (5, 6)]
    if not в_классе:
        return порядок
    место = {i: n for n, i in enumerate(в_классе)}
    вес = {i: n for n, i in enumerate(ПОРЯДОК_МАТЕМАТИКИ_5_6)}
    упорядоченные = sorted(в_классе, key=lambda i: (вес.get(i, len(вес) + место[i]),))
    новый = list(порядок)
    for n, i in enumerate(в_классе):
        новый[новый.index(i)] = упорядоченные[n] if False else новый[новый.index(i)]
    # заменяем позиции элементов класса по порядку
    позиции = [n for n, i in enumerate(порядок) if i in место]
    for поз, i in zip(позиции, упорядоченные):
        новый[поз] = i
    return новый

def класс_урока(L):
    """Класс из src по нижней границе; иначе — вручную; иначе None."""
    m = re.search(r"(\d{1,2})\s*(?:[–-]\s*(\d{1,2}))?\s*класс", str(L["src"]))
    if m:
        return int(m.group(1))
    return КЛАСС_ВРУЧНУЮ.get(L["id"])


def книга(L):
    """Название книги/раздела: текст src до слова «класс»."""
    src = str(L["src"])
    m = re.match(r"^(.*?)\s*·\s*\d{1,2}\s*(?:[–-]\s*\d{1,2})?\s*класс", src)
    if m:
        return m.group(1).strip()
    return src.split("·")[0].strip() or src


def младший(L):
    return L["subj"] == "jun" or "Начальная школа" in str(L["src"])



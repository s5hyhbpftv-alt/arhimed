def bars(items):
    out=[]
    for i,(lb,pct,val,cls) in enumerate(items):
        out.append(f'<div class="hbar {cls}"><span class="lb">{lb}</span><div class="track"><i style="width:{pct}%;animation-delay:{i*110}ms"></i></div><span class="val">{val}</span></div>')
